// Writes `.claude/skills/jgengine/recipes/cookbook.md` from `packages/core/src/recipes/*.recipe.test.ts`:
// each recipe's name, its one sentence and its test body verbatim, so the doc cannot drift from the test.
//
//   bun run gen recipes
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { printHelpIfAsked } from "./script-help";

export const RECIPES_DIR = "packages/core/src/recipes";
export const COOKBOOK = ".claude/skills/jgengine/recipes/cookbook.md";
const MIN_RECIPE_LINES = 5;
const MAX_RECIPE_LINES = 15;

export interface Recipe {
  name: string;
  sentence: string;
  imports: string[];
  body: string[];
}

/** Parse one recipe test file: the `@recipe` doc block, its imports and the body of its single test. */
export function parseRecipe(file: string, source: string): Recipe {
  const doc = /\/\*\*\s*\n\s*\*\s*@recipe\s+(.+)\n([\s\S]*?)\*\//.exec(source);
  const [, name, text] = doc ?? [];
  if (name === undefined || text === undefined) throw new Error(`${file}: no "@recipe <Feature>" doc block`);
  const sentence = text.split("\n").map((line) => line.replace(/^\s*\*\s?/, "").trim()).filter(Boolean).join(" ");
  if (sentence === "") throw new Error(`${file}: the doc block needs one sentence of what the feature is made of`);
  const tests = source.match(/^test\(/gm) ?? [];
  if (tests.length !== 1) throw new Error(`${file}: a recipe file holds exactly one test, found ${tests.length}`);
  const lines = source.split("\n");
  const start = lines.findIndex((line) => line.startsWith("test("));
  const end = lines.findIndex((line, index) => index > start && line === "});");
  if (end < 0) throw new Error(`${file}: the test does not close with "});" at column 0`);
  const body = lines.slice(start + 1, end).map((line) => line.replace(/^ {2}/, ""));
  const recipe = body.findIndex((line) => line.trim() === "");
  const recipeLines = recipe < 0 ? body.length : recipe;
  if (recipeLines < MIN_RECIPE_LINES || recipeLines > MAX_RECIPE_LINES) {
    throw new Error(`${file}: the recipe (lines before the first blank line) is ${recipeLines} lines; it must be ${MIN_RECIPE_LINES} to ${MAX_RECIPE_LINES}`);
  }
  const imports = lines.filter((line) => line.startsWith("import ") && !line.includes('"bun:test"'));
  if (imports.some((line) => /\.\.\/(?!parts"|random\/rng"|time\/cooldown"|anim\/easing"|world\/geometry")/.test(line))) {
    throw new Error(`${file}: a recipe imports parts only, not a feature folder`);
  }
  return { name: name.trim(), sentence, imports, body };
}

export function renderCookbook(recipes: readonly Recipe[]): string {
  const sections = recipes.map(
    (recipe) => `## ${recipe.name}\n\n${recipe.sentence}\n\n\`\`\`ts\n${[...recipe.imports.map((line) => line.replace(/"\.\.\//, '"@jgengine/core/')), "", ...recipe.body].join("\n")}\n\`\`\``,
  );
  return `# Cookbook

<!-- GENERATED by \`bun run gen recipes\` from ${RECIPES_DIR}/*.recipe.test.ts - edit the test, not this file. -->

Each common feature built from the parts in a few lines. The code is the test body, so it runs; the lines after the blank line check that it behaves.

${sections.join("\n\n")}
`;
}

function main(): void {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const dir = join(root, RECIPES_DIR);
  const files = readdirSync(dir).filter((name) => name.endsWith(".recipe.test.ts")).sort();
  const recipes = files.map((name) => parseRecipe(name, readFileSync(join(dir, name), "utf8")));
  const out = join(root, COOKBOOK);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, renderCookbook(recipes));
  console.log(`recipes OK - ${recipes.length} recipes`);
}

if (import.meta.main && !printHelpIfAsked("gen-cookbook", {
  summary: "write the jgengine skill's cookbook.md from the recipe tests in packages/core/src/recipes",
  usage: "bun run gen recipes",
  flags: [],
  example: "bun run gen recipes",
})) main();
