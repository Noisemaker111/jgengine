import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const DIRECTIVE =
  /(@ts-expect-error|@ts-ignore|@ts-nocheck|@jsxImportSource|\/\/\/\s*<reference|v8 ignore|istanbul ignore|c8 ignore|eslint-disable|biome-ignore|@__PURE__|#__PURE__|@vite-ignore|GENERATED by|SPDX-License-Identifier|Copyright|License\b|@skill\b|@recipe\b)/;

const METADATA_TAG = /@(capability|internal|deprecated)\b/;

// Keep comments that explain *why*, a constraint/invariant, lifecycle/ordering,
// ownership/disposal, platform quirk, units/ranges/coordinate space, or a non-obvious default.
const WHY_OR_CONTRACT = new RegExp(
  [
    // Causal / purpose / rationale
    String.raw`\b(?:because|so that|in order to|used by|used for|needed by|needed for|required by|required for|needed when|only when|unless|otherwise|instead of|rather than|fallback|to avoid|to prevent|to keep|to ensure|to guarantee|to match|to preserve|to stop|to allow|to let|for capture|for snapshot|for determinism|for perf|for performance|for safety|for compatibility|why)\b`,
    String.raw`\bso\s+(?:it|the|they|we|a|an|every|no|nothing|one|two|both|each|all|this|that|these|those|other|later|future|draws|callers|games|tests|consumers|clients|servers|frames|builds|imports|saves|reads|writes|changes|updates)\b`,
    // Constraints, invariants, lifecycle/ordering, ownership, data-safety
    String.raw`\b(?:never|must|must not|cannot|can't|do not|don't|won't|only once|runs once|before the|after the|in join order|order matters|remounts?|survives?|is cleared|while flushing|may join|may leave|caller owns|ownership|dispos(?:e|es|ed|al)|atomic|idempotent|thread-safe|re-entrant|cycle-safe|immutable|read-only|frozen|sealed|bounded|clamped|normalized|deterministic|durable|monotonic|invariant|workaround|quirk|caveat|gotcha|hack|pitfall|subtle|deliberate|intentional|safety|security|race|deadlock|leak|crash|freeze|stale|drift|silently|breaks?)\b`,
    String.raw`\bwould\s+(?:declare|break|fail|miss|drop|leak|corrupt|overwrite|lose|cause|stale|trigger|block|skip|race|crash)\b`,
    // Issue/PR refs, URLs, explicit callout markers, platform/backend specifics
    String.raw`#\d{3,}|https?:\/\/|\b(?:FIXME|BUG|HACK|WARNING|SAFETY|SECURITY|CAVEAT|INVARIANT|TODO)\b`,
    String.raw`\b(?:safari|firefox|webkit|chromium|windows|macos|linux|ios|android|webgl2?|webgpu|glsl|wgsl|three\.js|vite|bun|wasm|ssr|happy-dom|playwright|tailwind|convex|rapier|rune|gltf|glb|ktx2|ieee|nan|endian|utf-8|bom|crlf|symlink|junction|pcfshadowmap|srgb|acesfilmic|devicepixelratio)\b`,
    // Units, coordinate spaces, numeric ranges, non-obvious defaults, citations
    String.raw`\b(?:metres?|meters?|cm|mm|km|radians?|degrees?|seconds?|secs?|milliseconds?|ms|hz|fps|px|pixels?|texels?|bytes?|kb|mb|mib|gib|db|dbfs|lux|kelvin|watts?|newtons?|kg|m\/s|rad\/s|deg\/s|km\/h|mph|knots?|rpm|world-space|screen-space|clip-space|local-space|ndc|y-up|z-up|right-handed|left-handed|clockwise|counter-clockwise|ccw|cw|1-based|0-based)\b`,
    String.raw`\[\s*-?\d+(?:\.\d+)?\s*,\s*-?\d+(?:\.\d+)?\s*\]|\b-?\d+(?:\.\d+)?\s*\.\.\s*-?\d+(?:\.\d+)?\b|\[min,\s*max\]|\b0\s*(?:to|–|-)\s*1\b`,
    String.raw`\b(?:defaults? to|default(?:s)?\s*[:=]\s*[^\s.,;]+|when omitted|if omitted|omitted:|when undefined|null when|undefined when|returns null|returns undefined)\b`,
    String.raw`\((?:[A-Z][a-z]+[^)]{0,30})?(?:19|20)\d\d\)`,
  ].join("|"),
  "i",
);

const BANNER_LINE = /^\/\/\s*[-=*#~_]{3,}|^\/\/\s*[-=]{2,}\s+.*\s+[-=]{2,}\s*$/;
const COMMENTED_CODE_LINE =
  /^\/\/\s*(?:(?:export\s+)?(?:const|let|var|function|type|interface|class|import|return|throw|await|if|else|for|while|switch|case|break|continue)\s+[{(\w]|[\w$.]+\([^)]*\);?\s*$|\}\s*(?:else\s*\{)?\s*$)/;

function collectComments(sourceFile: ts.SourceFile, text: string) {
  const seen = new Map<number, { pos: number; end: number; kind: ts.SyntaxKind }>();
  const addRanges = (ranges: ts.CommentRange[] | undefined) => {
    if (!ranges) return;
    for (const r of ranges) {
      if (!seen.has(r.pos)) seen.set(r.pos, { pos: r.pos, end: r.end, kind: r.kind });
    }
  };
  function visit(node: ts.Node) {
    addRanges(ts.getLeadingCommentRanges(text, node.pos));
    addRanges(ts.getTrailingCommentRanges(text, node.end));
    ts.forEachChild(node, visit);
  }
  visit(sourceFile);
  addRanges(ts.getLeadingCommentRanges(text, sourceFile.endOfFileToken.pos));
  return [...seen.values()].sort((a, b) => a.pos - b.pos);
}

function stripJsdocStars(comment: string): string {
  return comment
    .slice(3, -2)
    .split(/\r?\n/)
    .map((l) => l.replace(/^\s*\*\s?/, "").trimEnd())
    .join("\n")
    .trim();
}

function proseBeforeTags(comment: string): string {
  const lines = stripJsdocStars(comment).split("\n");
  const prose: string[] = [];
  for (const line of lines) {
    if (/^\s*@[a-zA-Z]/.test(line)) break;
    prose.push(line);
  }
  return prose.join(" ").trim();
}

function trimJsdocToTags(comment: string, indent: string): string {
  const rawLines = stripJsdocStars(comment).split("\n");
  const keptTags: string[] = [];
  let capturing = false;
  let current = "";

  for (const line of rawLines) {
    const trimmed = line.trim();
    if (/^@[a-zA-Z]/.test(trimmed)) {
      if (capturing && current) keptTags.push(current);
      if (METADATA_TAG.test(trimmed)) {
        capturing = true;
        current = trimmed;
      } else {
        capturing = false;
        current = "";
      }
    } else if (capturing) {
      if (trimmed === "") {
        if (current) keptTags.push(current);
        capturing = false;
        current = "";
      } else {
        current = `${current} ${trimmed}`;
      }
    } else if (METADATA_TAG.test(trimmed)) {
      const m = trimmed.match(/@(?:capability|internal|deprecated)\b.*/);
      if (m) keptTags.push(m[0].trim());
    }
  }
  if (capturing && current) keptTags.push(current);

  if (keptTags.length === 0) return comment;
  if (keptTags.length === 1) return `/** ${keptTags[0]} */`;
  return `/**\n${keptTags.map((t) => `${indent} * ${t}`).join("\n")}\n${indent} */`;
}

function isJsxComment(text: string, pos: number, end: number): boolean {
  let i = pos - 1;
  while (i >= 0 && (text[i] === " " || text[i] === "\t" || text[i] === "\r" || text[i] === "\n")) i--;
  if (i < 0 || text[i] !== "{") return false;
  let j = end;
  while (j < text.length && (text[j] === " " || text[j] === "\t" || text[j] === "\r" || text[j] === "\n")) j++;
  return j < text.length && text[j] === "}";
}

export function shouldKeepCommentText(text: string): boolean {
  return DIRECTIVE.test(text) || WHY_OR_CONTRACT.test(text);
}

export function pruneFileComments(
  filePath: string,
  text: string,
): { next: string; removedLines: number; keptLines: number } {
  const sf = ts.createSourceFile(
    filePath,
    text,
    ts.ScriptTarget.Latest,
    false,
    filePath.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
  const comments = collectComments(sf, text);
  if (comments.length === 0) return { next: text, removedLines: 0, keptLines: 0 };

  const edits: Array<{ start: number; end: number; replacement: string }> = [];
  let removedLines = 0;
  let keptLines = 0;

  for (const c of comments) {
    const raw = text.slice(c.pos, c.end);
    const lineCount = raw.split(/\r?\n/).length;

    if (DIRECTIVE.test(raw) || isJsxComment(text, c.pos, c.end)) {
      keptLines += lineCount;
      continue;
    }

    let lineStart = c.pos;
    while (lineStart > 0 && text[lineStart - 1] !== "\n") lineStart--;
    const beforeOnLine = text.slice(lineStart, c.pos);
    const ownsLineStart = /^[ \t]*$/.test(beforeOnLine);

    let lineEnd = c.end;
    while (lineEnd < text.length && text[lineEnd] !== "\n") lineEnd++;
    const afterOnLine = text.slice(c.end, lineEnd);
    const ownsLineEnd = /^[ \t\r]*$/.test(afterOnLine);

    if (c.kind === ts.SyntaxKind.MultiLineCommentTrivia && raw.startsWith("/**")) {
      const prose = proseBeforeTags(raw);
      if (METADATA_TAG.test(raw)) {
        // Keep full JSDoc if prose carries a why/contract; otherwise collapse to metadata tags only.
        if (WHY_OR_CONTRACT.test(prose)) {
          keptLines += lineCount;
          continue;
        }
        const trimmed = trimJsdocToTags(raw, beforeOnLine);
        const newLines = trimmed.split(/\r?\n/).length;
        if (trimmed !== raw) {
          edits.push({ start: c.pos, end: c.end, replacement: trimmed });
          removedLines += lineCount - newLines;
        }
        keptLines += newLines;
        continue;
      }
      if (WHY_OR_CONTRACT.test(raw)) {
        keptLines += lineCount;
        continue;
      }
      if (ownsLineStart && ownsLineEnd) {
        const delEnd = lineEnd < text.length && text[lineEnd] === "\n" ? lineEnd + 1 : lineEnd;
        edits.push({ start: lineStart, end: delEnd, replacement: "" });
      } else {
        edits.push({ start: c.pos, end: c.end, replacement: "" });
      }
      removedLines += lineCount;
      continue;
    }

    if (c.kind === ts.SyntaxKind.MultiLineCommentTrivia) {
      if (WHY_OR_CONTRACT.test(raw)) {
        keptLines += lineCount;
        continue;
      }
      if (ownsLineStart && ownsLineEnd && (lineCount > 1 || /^\/\*\s*[-=*]{3,}/.test(raw))) {
        const delEnd = lineEnd < text.length && text[lineEnd] === "\n" ? lineEnd + 1 : lineEnd;
        edits.push({ start: lineStart, end: delEnd, replacement: "" });
        removedLines += lineCount;
        continue;
      }
      keptLines += lineCount;
      continue;
    }

    if (ownsLineStart && (BANNER_LINE.test(raw) || COMMENTED_CODE_LINE.test(raw))) {
      const delEnd = lineEnd < text.length && text[lineEnd] === "\n" ? lineEnd + 1 : lineEnd;
      edits.push({ start: lineStart, end: delEnd, replacement: "" });
      removedLines += 1;
      continue;
    }

    keptLines += 1;
  }

  if (edits.length === 0) return { next: text, removedLines: 0, keptLines };

  edits.sort((a, b) => b.start - a.start);
  let next = text;
  for (const e of edits) {
    next = next.slice(0, e.start) + e.replacement + next.slice(e.end);
  }
  next = next.replace(/\n{3,}/g, "\n\n").replace(/^\n+/, "");
  return { next, removedLines, keptLines };
}

function main() {
  const apply = process.argv.includes("--apply");
  const files = execSync("git ls-files", { encoding: "utf8" }).trim().split(/\r?\n/).filter(existsSync);
  const srcFiles = files.filter(
    (f) =>
      /\.(ts|tsx)$/.test(f) &&
      !/\.(test|spec)\.(ts|tsx)$/.test(f) &&
      !f.includes("vendor/") &&
      !f.endsWith(".d.ts") &&
      !f.startsWith("packages/jgengine/src/recipes/snippets/") &&
      !f.startsWith("apps/web/src/snippets/") &&
      f !== "packages/core/src/meta/changelog.ts" &&
      f !== "packages/core/src/meta/version.ts" &&
      f !== "scripts/prune-comments.ts",
  );

  let totalRemoved = 0;
  let totalKept = 0;
  let changedFiles = 0;
  let syntaxErrors = 0;

  for (const f of srcFiles) {
    const text = readFileSync(f, "utf8");
    const { next, removedLines, keptLines } = pruneFileComments(f, text);
    totalRemoved += removedLines;
    totalKept += keptLines;
    if (next !== text) {
      changedFiles++;
      const checkSf = ts.createSourceFile(
        f,
        next,
        ts.ScriptTarget.Latest,
        false,
        f.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
      ) as unknown as { parseDiagnostics?: unknown[] };
      if ((checkSf.parseDiagnostics?.length ?? 0) > 0) {
        syntaxErrors++;
        console.error("SYNTAX ERROR IN", f);
        continue;
      }
      if (apply) writeFileSync(f, next);
    }
  }

  console.log(
    `${apply ? "APPLIED" : "DRY RUN"}: ${changedFiles}/${srcFiles.length} files changed, -${totalRemoved} comment lines removed, ${totalKept} kept, ${syntaxErrors} syntax errors`,
  );
}

if (import.meta.main) main();
