import { afterEach, expect, test } from "bun:test";
import { mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";

import { columnKey, exportName, numberIn, pageHtml, readTables, renderDataFile, toDataTable } from "./data-table";

const made: string[] = [];
afterEach(() => {
  for (const dir of made.splice(0)) rmSync(dir, { recursive: true, force: true });
});

function scratch(): string {
  const dir = join(import.meta.dir, "..", ".scratch", `data-table-${crypto.randomUUID()}`);
  mkdirSync(dir, { recursive: true });
  made.push(dir);
  return dir;
}

// A wiki stats table as ark.wiki.gg lays it out: a two-row heading where "Health" spans its columns,
// a footnote marker, a hidden sort key, entities, a thousands separator and an empty cell.
const PAGE = `
<table class="navbox"><tr><td>Maps</td><td>The Island</td></tr></table>
<table class="wikitable">
  <caption>Base stats</caption>
  <tr><th rowspan="2"> Creature </th><th colspan="2"> Health </th><th rowspan="2">Base&#160;Damage</th></tr>
  <tr><th>Level 1</th><th>+W</th></tr>
  <tr><td><span class="sortkey">zz</span>Raptor<sup class="reference">[1]</sup></td><td>200</td><td>40</td><td>15</td></tr>
  <tr><td>Rex &amp; friends</td><td>1,100</td><td>-</td><td>10 / 40</td></tr>
</table>`;

test("reads a page's tables, nested navigation boxes included, in page order", async () => {
  const tables = await readTables(PAGE);
  expect(tables.length).toBe(2);
  expect(tables[1]!.caption).toBe("Base stats");
});

test("a two-row heading names each column, numbers are typed, and a mixed column stays text", async () => {
  const table = toDataTable((await readTables(PAGE))[1]!);
  expect(table.columns.map((column) => [column.key, column.type, column.nullable])).toEqual([
    ["creature", "string", false],
    ["healthLevel1", "number", false],
    ["healthW", "number", true],
    ["baseDamage", "string", false],
  ]);
  expect(table.rows).toEqual([
    ["Raptor", 200, 40, "15"],
    ["Rex & friends", 1100, null, "10 / 40"],
  ]);
});

test("the written file is TypeScript a game imports, and it names its source on line 1", async () => {
  const table = toDataTable((await readTables(PAGE))[1]!);
  const text = renderDataFile({ url: "https://wiki.test/Stats", index: 1, name: "creatureStats", table, fetched: "2026-10-26" });
  expect(text.split("\n")[0]).toBe("// GENERATED by `bun run data-table` from https://wiki.test/Stats (table 1). Re-run it with --refresh to update; do not edit.");
  const dir = scratch();
  const path = join(dir, "creatureStats.ts");
  await Bun.write(path, text);
  const loaded = (await import(path)) as { creatureStats: { creature: string; healthLevel1: number; healthW: number | null; baseDamage: string }[]; creatureStatsHeadings: Record<string, string> };
  expect(loaded.creatureStats[1]).toEqual({ creature: "Rex & friends", healthLevel1: 1100, healthW: null, baseDamage: "10 / 40" });
  expect(loaded.creatureStatsHeadings.healthW).toBe("Health +W");
});

test("a page is fetched once: the second read comes from the cache, --refresh goes back to the network", async () => {
  const cache = scratch();
  let fetches = 0;
  const fetchPage = async () => {
    fetches += 1;
    return `<p>fetch ${fetches}</p>`;
  };
  expect(await pageHtml("https://wiki.test/a", { refresh: false, cache, fetchPage })).toBe("<p>fetch 1</p>");
  expect(await pageHtml("https://wiki.test/a", { refresh: false, cache, fetchPage })).toBe("<p>fetch 1</p>");
  expect(fetches).toBe(1);
  expect(await pageHtml("https://wiki.test/a", { refresh: true, cache, fetchPage })).toBe("<p>fetch 2</p>");
  expect(await pageHtml("https://wiki.test/b", { refresh: false, cache, fetchPage })).toBe("<p>fetch 3</p>");
});

test("names and numbers", () => {
  expect(columnKey("Melee Damage (Wild)")).toBe("meleeDamageWild");
  expect(columnKey("2nd Attack")).toBe("col2ndAttack");
  expect(exportName("creatureStats")).toBe("creatureStats");
  expect(exportName("creature-stats")).toBe("creatureStats");
  expect([numberIn("1,200"), numberIn("+5"), numberIn("12.5%"), numberIn("−3"), numberIn("1-2"), numberIn("N/A")]).toEqual([1200, 5, 12.5, -3, null, null]);
});
