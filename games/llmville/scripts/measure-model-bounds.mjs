#!/usr/bin/env bun
/**
 * Measures tight mesh bounds for every worldModelCatalog entry with modelPath
 * and writes packages/game/src/scene/worldModelNativeExtents.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { Box3, Matrix4, Mesh, Vector3 } from "three";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";

import { WORLD_MODEL_CATALOG } from "../llmville/src/scene/worldModelCatalog.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const PUBLIC_MODELS = join(ROOT, "public");
const OUTPUT = join(ROOT, "packages/game/src/scene/worldModelNativeExtents.ts");

const _box = new Box3();
const _size = new Vector3();
const _center = new Vector3();
const _corner = new Vector3();
const _rootInverse = new Matrix4();

function measureObjectBounds(object) {
  object.updateMatrixWorld(true);
  _rootInverse.copy(object.matrixWorld).invert();

  const union = new Box3();
  let hasMesh = false;

  object.traverse((child) => {
    if (!(child instanceof Mesh)) return;
    const geometry = child.geometry;
    if (!geometry) return;
    if (!geometry.boundingBox) geometry.computeBoundingBox();
    if (!geometry.boundingBox) return;

    const meshBox = geometry.boundingBox;
    const corners = [
      [meshBox.min.x, meshBox.min.y, meshBox.min.z],
      [meshBox.min.x, meshBox.min.y, meshBox.max.z],
      [meshBox.min.x, meshBox.max.y, meshBox.min.z],
      [meshBox.min.x, meshBox.max.y, meshBox.max.z],
      [meshBox.max.x, meshBox.min.y, meshBox.min.z],
      [meshBox.max.x, meshBox.min.y, meshBox.max.z],
      [meshBox.max.x, meshBox.max.y, meshBox.min.z],
      [meshBox.max.x, meshBox.max.y, meshBox.max.z],
    ];

    child.updateMatrixWorld(true);
    const relativeMatrix = _rootInverse.clone().multiply(child.matrixWorld);

    for (const [x, y, z] of corners) {
      _corner.set(x, y, z).applyMatrix4(relativeMatrix);
      union.expandByPoint(_corner);
      hasMesh = true;
    }
  });

  if (!hasMesh) {
    _box.setFromObject(object);
  } else {
    _box.copy(union);
  }

  _box.getSize(_size);
  _box.getCenter(_center);

  return {
    width: Math.max(_size.x, 0.001),
    height: Math.max(_size.y, 0.001),
    depth: Math.max(_size.z, 0.001),
    center: [_center.x, _center.y, _center.z],
    minY: _box.min.y,
  };
}

async function loadModel(modelPath) {
  const filePath = join(PUBLIC_MODELS, modelPath.replace(/^\//, ""));
  const data = readFileSync(filePath);
  const loader = new GLTFLoader();
  const gltf = await loader.parseAsync(data.buffer, dirname(filePath));
  return gltf.scene;
}

function formatEntry(key, extents) {
  const center = `[${extents.center.map((v) => Number(v.toFixed(6))).join(", ")}]`;
  return `  ${key}: { width: ${extents.width.toFixed(6)}, height: ${extents.height.toFixed(6)}, depth: ${extents.depth.toFixed(6)}, center: ${center}, minY: ${extents.minY.toFixed(6)} },`;
}

async function main() {
  const entries = Object.entries(WORLD_MODEL_CATALOG).filter(([, asset]) => asset.modelPath);
  const extentsByKey = {};
  const measuredPaths = new Map();

  for (const [key, asset] of entries) {
    const modelPath = asset.modelPath;
    let extents = measuredPaths.get(modelPath);
    if (!extents) {
      process.stdout.write(`Measuring ${key} (${modelPath})... `);
      const scene = await loadModel(modelPath);
      extents = measureObjectBounds(scene);
      measuredPaths.set(modelPath, extents);
      console.log(`${extents.width.toFixed(2)} x ${extents.height.toFixed(2)} x ${extents.depth.toFixed(2)}`);
    }
    extentsByKey[key] = extents;
  }

  const lines = Object.keys(extentsByKey).sort().map((key) => formatEntry(key, extentsByKey[key]));
  const output = `/** Auto-generated by scripts/measure-model-bounds.mjs — do not edit manually. */
export interface NativeModelExtents {
  width: number;
  height: number;
  depth: number;
  center: [number, number, number];
  minY: number;
}

export const WORLD_MODEL_NATIVE_EXTENTS: Partial<Record<string, NativeModelExtents>> = {
${lines.join("\n")}
};
`;

  writeFileSync(OUTPUT, output, "utf8");
  console.log(`\nWrote ${Object.keys(extentsByKey).length} entries to ${OUTPUT}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});