function acceptsJson(request: import("http").IncomingMessage): boolean {
  const accept = request.headers.accept ?? "";
  // Agents/curl often send */* or application/json. Browsers send text/html first.
  // Return JSON when the client does not explicitly prefer HTML.
  if (accept.includes("text/html") && !accept.includes("application/json")) return false;
  return true;
}

