const SCREENSHOTS_DIR = path.resolve(__dirname, "public/dev-assets/screenshots");

interface ScreenshotAngleMeta {
  capturedAt: string;
  bytes: number;
}

interface ScreenshotBundleMeta {
  requestId: number;
  sceneVersion: number;
  capturedAt: string;
  angles: Partial<Record<BuilderScreenshotAngle, ScreenshotAngleMeta>>;
}

interface ScreenshotPendingRequest {
  requestId: number;
  angles: BuilderScreenshotAngle[];
  requestedAt: string;
  sceneVersion: number;
  uploaded: Set<BuilderScreenshotAngle>;
}

let nextScreenshotRequestId = 1;
let screenshotPending: ScreenshotPendingRequest | null = null;
let screenshotBundle: ScreenshotBundleMeta | null = null;

function queueViewportScreenshot(): number {
  const requestId = nextScreenshotRequestId++;
  screenshotPending = {
    requestId,
    angles: ["viewport"],
    requestedAt: new Date().toISOString(),
    sceneVersion: sceneState.version,
    uploaded: new Set(),
  };
  return requestId;
}

function screenshotFilePath(angle: BuilderScreenshotAngle): string {
  return path.join(SCREENSHOTS_DIR, `${angle}.png`);
}

function parseScreenshotQuery(requestUrl: string | undefined): URLSearchParams {
  const query = requestUrl?.includes("?") ? requestUrl.slice(requestUrl.indexOf("?") + 1) : "";
  return new URLSearchParams(query);
}

function screenshotStatusForQuery(query: URLSearchParams): {
  ready: boolean;
  stale: boolean;
  requestId: number | null;
  fulfilledRequestId: number | null;
  sceneVersion: number | null;
  capturedAt: string | null;
  pendingRequestId: number | null;
} {
  const minRequestId = Number.parseInt(query.get("requestId") ?? "", 10);
  const minSceneVersion = Number.parseInt(query.get("minVersion") ?? "", 10);
  const fulfilledRequestId = screenshotBundle?.requestId ?? null;
  const sceneVersion = screenshotBundle?.sceneVersion ?? null;
  const capturedAt = screenshotBundle?.capturedAt ?? null;
  const pendingRequestId = screenshotPending?.requestId ?? null;
  const requestReady = Number.isFinite(minRequestId)
    ? fulfilledRequestId !== null && fulfilledRequestId >= minRequestId
    : true;
  const versionReady = Number.isFinite(minSceneVersion)
    ? sceneVersion !== null && sceneVersion >= minSceneVersion
    : true;
  const ready = requestReady && versionReady && fulfilledRequestId !== null;
  const stale = !ready || (sceneState.version > (sceneVersion ?? 0)) || pendingRequestId !== null;
  return {
    ready,
    stale,
    requestId: fulfilledRequestId,
    fulfilledRequestId,
    sceneVersion,
    capturedAt,
    pendingRequestId,
  };
}

function markScreenshotAngleUploaded(
  angle: BuilderScreenshotAngle,
  bytes: number,
  requestId?: number,
  sceneVersion?: number,
): void {
  const capturedAt = new Date().toISOString();
  const activeRequestId = requestId ?? screenshotPending?.requestId ?? screenshotBundle?.requestId ?? 0;
  const activeSceneVersion = sceneVersion ?? screenshotPending?.sceneVersion ?? sceneState.version;
  screenshotBundle = {
    requestId: activeRequestId,
    sceneVersion: activeSceneVersion,
    capturedAt,
    angles: {
      ...(screenshotBundle?.angles ?? {}),
      [angle]: { capturedAt, bytes },
    },
  };

  if (screenshotPending && (requestId === undefined || requestId === screenshotPending.requestId)) {
    screenshotPending.uploaded.add(angle);
    if (screenshotPending.uploaded.size >= screenshotPending.angles.length) {
      screenshotBundle = {
        requestId: screenshotPending.requestId,
        sceneVersion: activeSceneVersion,
        capturedAt,
        angles: screenshotBundle.angles,
      };
      screenshotPending = null;
    }
  }
}

function builderScreenshotPlugin(): Plugin {
  return {
    name: "llmville-builder-screenshots",
    configureServer(server) {
      // GET  /__llmville-builder/screenshot — JSON index + status
      // POST /__llmville-builder/screenshot/request — ask the open browser tab to capture
      // GET  /__llmville-builder/screenshot/pending — browser poll for pending work
      // GET  /__llmville-builder/screenshot/{angle}.png — one capture
      // POST /__llmville-builder/screenshot — upload one angle (browser capture)
      server.middlewares.use("/__llmville-builder/screenshot", (request, response, next) => {
        const pathname = request.url?.split("?")[0] ?? "";
        const query = parseScreenshotQuery(request.url);
        const pngMatch = /^\/(viewport|perspective|top|side)\.png$/.exec(pathname);

        if (pngMatch && request.method === "GET") {
          const angle = pngMatch[1] as BuilderScreenshotAngle;
          void fs.readFile(screenshotFilePath(angle))
            .then((buffer) => {
              response.setHeader("content-type", "image/png");
              response.setHeader("cache-control", "no-cache");
              response.end(buffer);
            })
            .catch(() => {
              response.statusCode = 404;
              response.setHeader("content-type", "application/json");
              response.end(JSON.stringify({ error: `No screenshot available for ${angle}` }));
            });
          return;
        }

        if (pathname === "/request" && request.method === "POST") {
          void (async () => {
            const body = await readJsonBody(request).catch(() => ({}));
            const angles = parseCaptureAngles(isRecord(body) ? body.angles : undefined);
            if (!angles) {
              response.statusCode = 400;
              response.setHeader("content-type", "application/json");
              response.end(JSON.stringify({ error: `angles must be a subset of ${BUILDER_SCREENSHOT_ANGLES.join(", ")}` }));
              return;
            }
            const requestId = nextScreenshotRequestId++;
            screenshotPending = {
              requestId,
              angles,
              requestedAt: new Date().toISOString(),
              sceneVersion: sceneState.version,
              uploaded: new Set(),
            };
            const host = request.headers.host ?? "localhost:3001";
            const origin = `http://${host}`;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({
              requestId,
              status: "pending",
              angles,
              poll: `${origin}/__llmville-builder/screenshot?requestId=${requestId}`,
              viewport: `${origin}/__llmville-builder/screenshot/viewport.png`,
              hint: "Keep /dev/build open in a browser tab. Poll GET /screenshot?requestId=N until status.ready is true, then GET viewport.png.",
            }));
          })().catch((error: unknown) => {
            response.statusCode = 500;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Screenshot request failed" }));
          });
          return;
        }

        if (pathname === "/pending" && request.method === "GET") {
          response.setHeader("content-type", "application/json");
          if (!screenshotPending) {
            response.end(JSON.stringify({ requestId: null }));
            return;
          }
          response.end(JSON.stringify({
            requestId: screenshotPending.requestId,
            angles: screenshotPending.angles,
            sceneVersion: screenshotPending.sceneVersion,
            requestedAt: screenshotPending.requestedAt,
          }));
          return;
        }

        if (pathname !== "/") {
          next();
          return;
        }

        if (request.method === "POST") {
          void (async () => {
            const body = await readJsonBody(request) as {
              angle?: unknown;
              image?: unknown;
              requestId?: unknown;
              sceneVersion?: unknown;
            };
            if (!isRecord(body) || typeof body.angle !== "string" || typeof body.image !== "string") {
              response.statusCode = 400;
              response.setHeader("content-type", "application/json");
              response.end(JSON.stringify({ error: "Body must contain { angle: string, image: base64_string }" }));
              return;
            }
            const angle = body.angle;
            if (!BUILDER_SCREENSHOT_ANGLES.includes(angle as BuilderScreenshotAngle)) {
              response.statusCode = 400;
              response.setHeader("content-type", "application/json");
              response.end(JSON.stringify({ error: `angle must be one of ${BUILDER_SCREENSHOT_ANGLES.join(", ")}` }));
              return;
            }
            const base64 = body.image.replace(/^data:image\/png;base64,/, "");
            const buffer = Buffer.from(base64, "base64");
            await fs.mkdir(SCREENSHOTS_DIR, { recursive: true });
            await fs.writeFile(screenshotFilePath(angle as BuilderScreenshotAngle), buffer);
            const requestId = typeof body.requestId === "number" ? body.requestId : undefined;
            const sceneVersion = typeof body.sceneVersion === "number" ? body.sceneVersion : undefined;
            markScreenshotAngleUploaded(angle as BuilderScreenshotAngle, buffer.length, requestId, sceneVersion);
            response.statusCode = 204;
            response.end();
          })().catch((error: unknown) => {
            response.statusCode = 500;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Screenshot save failed" }));
          });
          return;
        }

        if (request.method === "GET") {
          void (async () => {
            const host = request.headers.host ?? "localhost:3001";
            const origin = `http://${host}`;
            const images: Record<string, string> = {};
            await fs.mkdir(SCREENSHOTS_DIR, { recursive: true });
            for (const angle of BUILDER_SCREENSHOT_ANGLES) {
              try {
                await fs.access(screenshotFilePath(angle));
                images[angle] = `/__llmville-builder/screenshot/${angle}.png`;
              } catch {
                // skip missing angles
              }
            }
            const guide = buildBuilderAgentPlaybook(origin).screenshots;
            const status = screenshotStatusForQuery(query);
            const payload = {
              meta: {
                usage: guide.workflow,
                verifyWorkflow: guide.verifyWorkflow,
                prerequisite: guide.prerequisite,
                staleCaptureHint: guide.staleCaptureHint,
                angles: BUILDER_SCREENSHOT_ANGLES,
                playbook: `${origin}/__llmville-builder/playbook`,
                openapi: `${origin}/dev-assets/builder-api.openapi.json`,
                exampleFetch: `curl -o viewport.png ${origin}/__llmville-builder/screenshot/viewport.png`,
                requestCapture: `curl -X POST ${origin}/__llmville-builder/screenshot/request`,
              },
              status,
              ...images,
            };
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify(payload));
          })().catch((error: unknown) => {
            response.statusCode = 500;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Screenshot read failed" }));
          });
          return;
        }

        next();
      });
    },
  };
}

function builderAgentApiPlugin(): Plugin {
  return {
    name: "llmville-builder-agent-api",
    configureServer(server) {
      void loadSourceLibraryFromDisk().then((entries) => {
        cachedSourceLibraryEntries = entries;
      });

      server.middlewares.use("/__llmville-builder/status", (request, response, next) => {
        if (request.method !== "GET") {
          next();
          return;
        }
        const host = request.headers.host ?? "localhost:3001";
        const origin = `http://${host}`;
        const browserConnected = sceneState.browserLastSeen !== null && Date.now() - sceneState.browserLastSeen < 8000;
        const status = screenshotStatusForQuery(new URLSearchParams());
        response.setHeader("content-type", "application/json");
        response.end(JSON.stringify({
          scene: publicScenePayload(sceneState),
          browserConnected,
          screenshot: status,
          hints: browserConnected
            ? ["Browser tab is live — POST /screenshot/request with {\"angles\":[\"viewport\"]} to verify."]
            : ["Open /dev/build in a browser tab before requesting screenshots or expecting live sync."],
          endpoints: {
            createAsset: `${origin}/__llmville-builder/assets`,
            scene: `${origin}/__llmville-builder/scene`,
            screenshotRequest: `${origin}/__llmville-builder/screenshot/request`,
            playbook: `${origin}/__llmville-builder/playbook`,
          },
        }));
      });

      server.middlewares.use("/__llmville-builder/heartbeat", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        sceneState = { ...sceneState, browserLastSeen: Date.now() };
        response.statusCode = 204;
        response.end();
      });

      server.middlewares.use("/__llmville-builder/assets", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        void (async () => {
          const body = await readJsonBody(request);
          const assetRequest = parseAgentAssetRequest(body);
          if (!assetRequest) {
            response.statusCode = 400;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({
              error: "Body must contain { id, label, decor } where decor.type is box|sphere|cylinder|plane|group|model.",
            }));
            return;
          }

          const entry = buildAgentAssetLibraryEntry(assetRequest);
          const mapData = buildIsolatedAgentAssetScene(entry.decor);
          bumpSceneState(request, mapData);

          let savedTo: string[] = [];
          if (assetRequest.save) {
            const merged = mergeSourceLibraryEntry(cachedSourceLibraryEntries, entry);
            await persistSourceLibraryEntries(merged);
            await persistBuilderLibraryJson(merged);
            savedTo = [
              "llmville/src/dev/builder/assetLibrary.ts",
              "llmville/public/dev-assets/builder-library.json",
            ];
          }

          const screenshotRequestId = assetRequest.verify ? queueViewportScreenshot() : null;
          const host = request.headers.host ?? "localhost:3001";
          const origin = `http://${host}`;
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({
            ok: true,
            entry,
            scene: publicScenePayload(sceneState),
            savedTo,
            screenshot: screenshotRequestId
              ? {
                  requestId: screenshotRequestId,
                  poll: `${origin}/__llmville-builder/screenshot?requestId=${screenshotRequestId}`,
                  viewport: `${origin}/__llmville-builder/screenshot/viewport.png`,
                }
              : null,
            nextSteps: [
              "Poll GET /status or /screenshot?requestId=N until screenshot.ready (if verify=true).",
              "GET /screenshot/viewport.png to inspect the object.",
              "User can refine in /dev/build, then POST /source-library again if needed.",
            ],
          }));
        })().catch((error: unknown) => {
          response.statusCode = 500;
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Asset create failed" }));
        });
      });
    },
  };
}

