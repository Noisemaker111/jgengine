function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** The entry type has a single source of truth in `builderLibrary.ts` — only data is generated here. */
function serializeBuilderSourceLibrary(entries: unknown[]): string {
  return `import type { BuilderAssetLibraryEntry } from "@/dev/builder/builderLibrary";

/** Dev-only saved library entries promoted from the builder.
 *  Regenerated by the \`/__llmville-builder/source-library\` dev endpoint. */
export const DEV_BUILDER_ASSET_LIBRARY: readonly BuilderAssetLibraryEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

function parseSourceLibraryRequest(body: string): unknown[] {
  const parsed = JSON.parse(body) as unknown;
  if (!isRecord(parsed) || !Array.isArray(parsed.entries)) {
    throw new Error("Request body must be JSON with an entries array.");
  }
  for (const entry of parsed.entries) {
    if (!isRecord(entry) || typeof entry.id !== "string" || typeof entry.label !== "string") {
      throw new Error("Every source asset entry must include string id and label.");
    }
    if (entry.kind !== "group" && entry.kind !== "place" && entry.kind !== "street") {
      throw new Error(`Source asset ${entry.id} has invalid kind.`);
    }
  }
  return parsed.entries;
}

function builderAgentPlugin(): Plugin {
  return {
    name: "llmville-builder-agent",
    configureServer(server) {
      server.middlewares.use("/__llmville-builder/generate", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        let body = "";
        request.setEncoding("utf8");
        request.on("data", (chunk: string) => {
          body += chunk;
        });
        request.on("end", () => {
          void (async () => {
            let prompt = "";
            try {
              const parsed = JSON.parse(body) as { prompt?: unknown };
              if (typeof parsed.prompt === "string") prompt = parsed.prompt;
            } catch {
              // fall through to the empty-prompt error below
            }
            // Load through vite's SSR pipeline: a bare `import()` here would be
            // resolved by node at config-bundle load time, which cannot handle
            // the `@/` alias or extensionless workspace TS imports.
            const { generateBuilderAsset } = await server.ssrLoadModule(
              "/builderAgent.server.ts",
            ) as typeof import("./builderAgent.server");
            const result = prompt.trim()
              ? await generateBuilderAsset(prompt)
              : { error: "Request body must be JSON with a non-empty \"prompt\" string." };
            response.statusCode = result.error ? 502 : 200;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify(result));
          })().catch((error: unknown) => {
            response.statusCode = 500;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Builder agent failed" }));
          });
        });
      });
    },
  };
}

