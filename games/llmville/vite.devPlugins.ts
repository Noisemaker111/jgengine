// ── Builder scene state (server-side, shared between browser and agents) ──

type BuilderSceneSource = "agent" | "browser";

interface BuilderSceneState {
  mapData: unknown;
  version: number;
  history: string[];
  updatedBy: BuilderSceneSource;
  updatedAt: string;
  browserLastSeen: number | null;
}

function sceneSourceFromRequest(request: import("http").IncomingMessage): BuilderSceneSource {
  const header = request.headers["x-llmville-builder-source"];
  return header === "browser" ? "browser" : "agent";
}

function markSceneMutation(source: BuilderSceneSource): Pick<BuilderSceneState, "updatedBy" | "updatedAt"> {
  return {
    updatedBy: source,
    updatedAt: new Date().toISOString(),
  };
}

function publicScenePayload(state: BuilderSceneState) {
  const browserConnected = state.browserLastSeen !== null && Date.now() - state.browserLastSeen < 8000;
  return {
    mapData: state.mapData,
    version: state.version,
    updatedBy: state.updatedBy,
    updatedAt: state.updatedAt,
    browserConnected,
    browserLastSeen: state.browserLastSeen,
  };
}

