// Bridge protocol for `/__llmville-builder/api/*`: HTTP requests hitting this
// dev server are relayed to the live BuilderStore in whatever browser tab has
// `/dev/build` open, over Vite's HMR websocket (`server.ws` here, matched by
// `import.meta.hot` in `src/dev/builder/executorBridge.ts`). There's no shared
// import between the two sides (this file can't load `@/`-aliased modules —
// see the file-level constraint noted elsewhere in this file), so the payload
// shapes are duplicated in both places and must be kept in sync by hand.
type ExecutorBridgeRequest =
  | { id: number; kind: "call"; method: string; args: unknown[] }
  | { id: number; kind: "scene" }
  | { id: number; kind: "listMethods" };
type ExecutorBridgeResponse = { id: number; ok: boolean; payload: unknown };

declare module "vite/types/customEvent.d.ts" {
  interface CustomEventMap {
    "llmville:executor:request": ExecutorBridgeRequest;
    "llmville:executor:response": ExecutorBridgeResponse;
  }
}

function builderExecutorApiPlugin(): Plugin {
  return {
    name: "llmville-builder-executor-api",
    configureServer(server) {
      let nextRequestId = 0;
      const pending = new Map<number, {
        resolve: (payload: unknown) => void;
        reject: (error: Error) => void;
        timer: ReturnType<typeof setTimeout>;
      }>();

      server.ws.on("llmville:executor:response", (data) => {
        const entry = pending.get(data.id);
        if (!entry) return;
        clearTimeout(entry.timer);
        pending.delete(data.id);
        if (data.ok) entry.resolve(data.payload);
        else entry.reject(new Error(typeof data.payload === "string" ? data.payload : "Builder client reported an error."));
      });

      // Sends a request over the HMR socket and resolves/rejects once the
      // browser tab replies (or after a timeout). Rejects immediately with
      // "no-client" if no tab is currently connected — callers use that to
      // short-circuit into a 503 without waiting out the timeout.
      function bridgeRequest(kind: "call" | "scene" | "listMethods", extra?: { method?: string; args?: unknown[] }): Promise<unknown> {
        if (server.ws.clients.size === 0) {
          return Promise.reject(new Error("no-client"));
        }
        const id = nextRequestId++;
        return new Promise<unknown>((resolve, reject) => {
          const timer = setTimeout(() => {
            pending.delete(id);
            reject(new Error("timeout"));
          }, 75_000);
          pending.set(id, { resolve, reject, timer });
          const request: ExecutorBridgeRequest = kind === "call"
            ? { id, kind: "call", method: extra?.method ?? "", args: extra?.args ?? [] }
            : kind === "scene"
              ? { id, kind: "scene" }
              : { id, kind: "listMethods" };
          server.ws.send("llmville:executor:request", request);
        });
      }

      server.middlewares.use("/__llmville-builder/openapi.json", (request, response, next) => {
        if (request.method !== "GET") {
          next();
          return;
        }
        void (async () => {
          const host = request.headers.host;
          const baseUrl = host
            ? `http://${host}/__llmville-builder/api`
            : "http://localhost:3001/__llmville-builder/api";

          // Prefer the client's live-enumerated method names (source-confirmed
          // public subset) when a tab is connected; otherwise fall back to the
          // extraction-only path inside buildOpenApiSpec (methodNames: []).
          let methodNames: string[] = [];
          if (server.ws.clients.size > 0) {
            try {
              const raw = await bridgeRequest("listMethods");
              const names = Array.isArray(raw) ? raw.filter((item): item is string => typeof item === "string") : [];
              const { resolvePublicMethods } = await server.ssrLoadModule(
                "/builderChatAgent.server.ts",
              ) as typeof import("./builderChatAgent.server");
              const resolved = await resolvePublicMethods(names, server.config.root);
              methodNames = resolved.names;
            } catch {
              methodNames = [];
            }
          }

          const { buildOpenApiSpec } = await server.ssrLoadModule(
            "/builderExecutorApi.server.ts",
          ) as typeof import("./builderExecutorApi.server");
          const spec = await buildOpenApiSpec({ rootDir: server.config.root, methodNames, baseUrl });
          response.statusCode = 200;
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify(spec));
        })().catch((error: unknown) => {
          response.statusCode = 500;
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Failed to build OpenAPI spec" }));
        });
      });

      server.middlewares.use("/__llmville-builder/api/call/", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        // `server.middlewares.use(prefix, fn)` strips the matched prefix off
        // `request.url`, leaving just the method segment (e.g. "/moveSelection").
        const method = decodeURIComponent((request.url ?? "").split("?")[0].replace(/^\/+/, ""));
        if (!method) {
          next();
          return;
        }

        let body = "";
        request.setEncoding("utf8");
        request.on("data", (chunk: string) => {
          body += chunk;
        });
        request.on("end", () => {
          void (async () => {
            let args: unknown[] = [];
            if (body.trim()) {
              try {
                const parsed = JSON.parse(body) as { args?: unknown };
                if (Array.isArray(parsed.args)) args = parsed.args;
              } catch {
                response.statusCode = 400;
                response.setHeader("content-type", "application/json");
                response.end(JSON.stringify({ error: 'Request body must be JSON with an optional "args" array.' }));
                return;
              }
            }

            if (server.ws.clients.size === 0) {
              response.statusCode = 503;
              response.setHeader("content-type", "application/json");
              response.end(JSON.stringify({ error: "no builder client connected — open /dev/build in a browser" }));
              return;
            }

            try {
              const payload = await bridgeRequest("call", { method, args });
              response.statusCode = 200;
              response.setHeader("content-type", "application/json");
              response.end(JSON.stringify(payload));
            } catch (error) {
              // Timeout/no-client-mid-flight vs. a genuine error reported by the
              // browser side: a failed *tool call* still comes back as a
              // resolved bridge payload with ExecutedCall.ok === false (HTTP 200)
              // — only bridge-level rejections land here.
              const message = error instanceof Error ? error.message : "Builder executor call failed";
              response.statusCode = message === "timeout" ? 504 : 502;
              response.setHeader("content-type", "application/json");
              response.end(JSON.stringify({
                error: message === "timeout" ? "builder client did not respond in time" : message,
              }));
            }
          })().catch((error: unknown) => {
            response.statusCode = 500;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Builder executor call failed" }));
          });
        });
      });

      server.middlewares.use("/__llmville-builder/api/scene", (request, response, next) => {
        if (request.method !== "GET") {
          next();
          return;
        }
        void (async () => {
          if (server.ws.clients.size === 0) {
            response.statusCode = 503;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: "no builder client connected — open /dev/build in a browser" }));
            return;
          }

          try {
            const payload = await bridgeRequest("scene");
            response.statusCode = 200;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify(payload));
          } catch (error) {
            const message = error instanceof Error ? error.message : "Builder executor scene request failed";
            response.statusCode = message === "timeout" ? 504 : 502;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({
              error: message === "timeout" ? "builder client did not respond in time" : message,
            }));
          }
        })().catch((error: unknown) => {
          response.statusCode = 500;
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Builder executor scene request failed" }));
        });
      });
    },
  };
}

