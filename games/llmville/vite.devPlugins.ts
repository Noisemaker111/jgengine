let sceneState: BuilderSceneState = createDefaultScene();
let cachedSourceLibraryEntries: unknown[] = [];

async function loadSourceLibraryFromDisk(): Promise<unknown[]> {
  try {
    const raw = await fs.readFile(builderSourceLibraryPath, "utf8");
    const match = /DEV_BUILDER_ASSET_LIBRARY[^[]*(\[[\s\S]*?\])\s*;/.exec(raw);
    if (!match) return [];
    return JSON.parse(match[1]) as unknown[];
  } catch {
    return [];
  }
}

async function persistSourceLibraryEntries(entries: unknown[]): Promise<void> {
  cachedSourceLibraryEntries = entries;
  await fs.writeFile(builderSourceLibraryPath, serializeBuilderSourceLibrary(entries), "utf8");
}

async function persistBuilderLibraryJson(entries: unknown[]): Promise<void> {
  await fs.mkdir(path.dirname(builderLibraryPath), { recursive: true });
  await fs.writeFile(builderLibraryPath, JSON.stringify(entries, null, 2), "utf8");
}

function mergeSourceLibraryEntry(entries: unknown[], entry: unknown): unknown[] {
  if (!isRecord(entry) || typeof entry.id !== "string") return entries;
  const replaced = entries.some((candidate) => isRecord(candidate) && candidate.id === entry.id);
  return replaced
    ? entries.map((candidate) => (isRecord(candidate) && candidate.id === entry.id ? entry : candidate))
    : [...entries, entry];
}


const MAX_SCENE_HISTORY = 50;

function pushSceneHistory(current: BuilderSceneState): void {
  const nextHistory = [...current.history, JSON.stringify(current.mapData)];
  sceneState = {
    ...current,
    history: nextHistory.length > MAX_SCENE_HISTORY ? nextHistory.slice(-MAX_SCENE_HISTORY) : nextHistory,
  };
}

function bumpSceneState(
  request: import("http").IncomingMessage,
  mapData: unknown,
): BuilderSceneState {
  const source = sceneSourceFromRequest(request);
  pushSceneHistory(sceneState);
  sceneState = {
    ...sceneState,
    mapData,
    version: sceneState.version + 1,
    ...markSceneMutation(source),
  };
  return sceneState;
}

function readJsonBody(request: import("http").IncomingMessage): Promise<unknown> {
  return new Promise((resolve, reject) => {
    let body = "";
    request.setEncoding("utf8");
    request.on("data", (chunk: string) => {
      body += chunk;
    });
    request.on("end", () => {
      try {
        resolve(JSON.parse(body));
      } catch {
        reject(new Error("Invalid JSON body"));
      }
    });
    request.on("error", reject);
  });
}

function builderScenePlugin(): Plugin {
  return {
    name: "llmville-builder-scene",
    configureServer(server) {
      server.middlewares.use("/__llmville-builder/scene", (request, response, next) => {
        const pathname = request.url?.split("?")[0] ?? "";
        // Connect strips the mount path from request.url.
        // Exact /__llmville-builder/scene becomes "/"; sub-routes become "/place", etc.
        if (pathname !== "/") {
          next();
          return;
        }

        // GET /__llmville-builder/scene — read current scene
        if (request.method === "GET") {
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify(publicScenePayload(sceneState)));
          return;
        }

        // POST /__llmville-builder/scene — replace full scene
        if (request.method === "POST") {
          void (async () => {
            const body = await readJsonBody(request) as { mapData?: unknown };
            if (!isRecord(body) || !body.mapData) {
              response.statusCode = 400;
              response.setHeader("content-type", "application/json");
              response.end(JSON.stringify({ error: "Body must contain { mapData }" }));
              return;
            }
            const source = sceneSourceFromRequest(request);
            pushSceneHistory(sceneState);
            sceneState = {
              mapData: body.mapData,
              version: sceneState.version + 1,
              history: sceneState.history,
              browserLastSeen: sceneState.browserLastSeen,
              ...markSceneMutation(source),
            };
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify(publicScenePayload(sceneState)));
          })().catch((error: unknown) => {
            response.statusCode = 500;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Scene update failed" }));
          });
          return;
        }

        next();
      });

      server.middlewares.use("/__llmville-builder/scene/place", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        void (async () => {
          const body = await readJsonBody(request) as { decor?: unknown; items?: unknown[] };
          if (!isRecord(body)) {
            response.statusCode = 400;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: "Invalid body" }));
            return;
          }

          const items = Array.isArray(body.items) ? body.items : body.decor ? [body.decor] : [];
          if (items.length === 0) {
            response.statusCode = 400;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: "Provide decor or items array" }));
            return;
          }

          const mapData = isRecord(sceneState.mapData) ? { ...sceneState.mapData } : {};
          const decor = Array.isArray(mapData.decor) ? [...mapData.decor] : [];
          const placed: unknown[] = [];

          for (const raw of items) {
            if (!isRecord(raw)) continue;
            const item = { ...raw };
            if (!item.id) {
              const used = new Set(decor.map((d: unknown) => isRecord(d) && typeof d.id === "string" ? d.id : ""));
              let id = `agent_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;
              let suffix = 2;
              while (used.has(id)) {
                id = `agent_${Date.now()}_${suffix}_${Math.random().toString(36).slice(2, 5)}`;
                suffix += 1;
              }
              item.id = id;
            }
            decor.push(item);
            placed.push(item);
          }

          bumpSceneState(request, { ...mapData, decor });

          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ placed, ...publicScenePayload(sceneState) }));
        })().catch((error: unknown) => {
          response.statusCode = 500;
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Place failed" }));
        });
      });

      server.middlewares.use("/__llmville-builder/scene/delete", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        void (async () => {
          const body = await readJsonBody(request) as { ids?: unknown };
          if (!isRecord(body) || !Array.isArray(body.ids)) {
            response.statusCode = 400;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: "Body must contain { ids: string[] }" }));
            return;
          }
          const ids = new Set(body.ids.filter((id): id is string => typeof id === "string"));
          const mapData = isRecord(sceneState.mapData) ? { ...sceneState.mapData } : {};
          const decor = Array.isArray(mapData.decor)
            ? mapData.decor.filter((d: unknown) => {
              if (!isRecord(d)) return true;
              return typeof d.id !== "string" || !ids.has(d.id);
            })
            : [];

          bumpSceneState(request, { ...mapData, decor });

          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ deleted: ids.size, ...publicScenePayload(sceneState) }));
        })().catch((error: unknown) => {
          response.statusCode = 500;
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Delete failed" }));
        });
      });

      server.middlewares.use("/__llmville-builder/scene/move", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        void (async () => {
          const raw = await readJsonBody(request) as { id?: unknown; position?: unknown; rotation?: unknown };
          if (!isRecord(raw) || typeof raw.id !== "string" || !Array.isArray(raw.position) || raw.position.length < 3) {
            response.statusCode = 400;
            response.setHeader("content-type", "application/json");
            response.end(JSON.stringify({ error: "Body must contain { id, position: [x,y,z], rotation?: [x,y,z] }" }));
            return;
          }
          const body = raw as { id: string; position: unknown[]; rotation?: unknown };
          const mapData = isRecord(sceneState.mapData) ? { ...sceneState.mapData } : {};
          const decor = Array.isArray(mapData.decor) ? mapData.decor.map((d: unknown) => {
            if (!isRecord(d) || d.id !== body.id) return d;
            const next: Record<string, unknown> = { ...d, position: body.position.slice(0, 3) };
            if (Array.isArray(body.rotation) && body.rotation.length >= 3) {
              next.rotation = body.rotation.slice(0, 3);
            }
            return next;
          }) : [];

          bumpSceneState(request, { ...mapData, decor });

          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify(publicScenePayload(sceneState)));
        })().catch((error: unknown) => {
          response.statusCode = 500;
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ error: error instanceof Error ? error.message : "Move failed" }));
        });
      });

      server.middlewares.use("/__llmville-builder/scene/clear", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        const mapData = isRecord(sceneState.mapData) ? { ...sceneState.mapData } : {};
        bumpSceneState(request, { ...mapData, decor: [], walls: [] });
        response.setHeader("content-type", "application/json");
        response.end(JSON.stringify(publicScenePayload(sceneState)));
      });

      server.middlewares.use("/__llmville-builder/scene/undo", (request, response, next) => {
        if (request.method !== "POST") {
          next();
          return;
        }
        if (sceneState.history.length === 0) {
          response.setHeader("content-type", "application/json");
          response.end(JSON.stringify({ version: sceneState.version, undone: false, reason: "No history" }));
          return;
        }
        const previous = sceneState.history[sceneState.history.length - 1];
        sceneState = {
          ...sceneState,
          mapData: JSON.parse(previous),
          version: sceneState.version + 1,
          history: sceneState.history.slice(0, -1),
          ...markSceneMutation(sceneSourceFromRequest(request)),
        };
        response.setHeader("content-type", "application/json");
        response.end(JSON.stringify({ ...publicScenePayload(sceneState), undone: true }));
      });
    },
  };
}

