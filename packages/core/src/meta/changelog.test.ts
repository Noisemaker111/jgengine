import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { VERSION } from "./changelog";

const source = readFileSync(join(import.meta.dir, "changelog.ts"), "utf8");

/**
 * `bun run release` and `bun run version:release` rewrite this file, and the header is what stops
 * `check:fix-has-test` asking a release diff of a generated mirror for a test (#2232). A
 * regeneration that drops it must fail here, not silently turn the mirror back into runtime source.
 */
test("the generated mirror keeps its GENERATED header", () => {
  const head = source.split("\n", 1)[0]!;
  expect(head).toStartWith("// GENERATED by ");
  expect(head).toContain("Regenerate:");
});

test("its VERSION matches the package it ships in", () => {
  const pkg = JSON.parse(readFileSync(join(import.meta.dir, "..", "..", "package.json"), "utf8")) as { version: string };
  expect(VERSION).toBe(pkg.version);
});
