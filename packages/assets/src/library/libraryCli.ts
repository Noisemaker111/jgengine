/** The sources `assets library ingest` can refresh, each writing `library/generated/<source>.json`. */
const INGESTERS: Record<string, (options: IngestOptions) => Promise<LibraryRecord[]>> = {
  ambientcg: ingestAmbientcg,
  polyhaven: ingestPolyhaven,
  gameicons: ingestGameicons,
  sketchfab: ingestSketchfab,
  rocketbox: ingestRocketbox,
  makehuman: async () => makehumanRecords(),
  kaykit: (options) => ingestKaykitTrees(kaykitTreePacks(), options),
};

/** KayKit packs the pack index has not measured yet, listed from their repository trees. */
function kaykitTreePacks(): KayKitTreePack[] {
  return kaykitSources.flatMap((source) => {
    if (source.unpulled === undefined || !("url" in source.download)) return [];
    const repo = /KayKit-Game-Assets\/([^/]+)\//.exec(source.download.url)?.[1];
    return repo === undefined ? [] : [{ pack: source.id, repo, tags: source.categories }];
  });
}

function flag(argv: readonly string[], name: string): string | undefined {
  const index = argv.indexOf(`--${name}`);
  return index >= 0 ? argv[index + 1] : undefined;
}

function positional(argv: readonly string[]): string[] {
  const out: string[] = [];
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index] ?? "";
    if (value.startsWith("--")) {
      if (!["--json", "--no-credit"].includes(value)) index += 1;
      continue;
    }
    out.push(value);
  }
  return out;
}

/**
 * Writes one ingest file and rewrites the barrel that imports every committed file.
 *
 * @internal
 */
export function writeLibraryFile(generatedDir: string, file: LibraryRecordFile): void {
  writeFileSync(join(generatedDir, `${file.source}.json`), `${JSON.stringify(file)}\n`);
  const ids = readdirSync(generatedDir)
    .filter((name) => name.endsWith(".json"))
    .map((name) => name.replace(/\.json$/, ""))
    .sort();
  const imports = ids.map((id) => `import s_${id} from "./${id}.json" with { type: "json" };`).join("\n");
  const list = ids.map((id) => `  s_${id},`).join("\n");
  writeFileSync(
    join(generatedDir, "index.ts"),
    `// AUTO-GENERATED by \`assets library ingest\`. Do not edit by hand.\n${imports}\n\n/** Every committed library ingest file, as untyped JSON; \`readLibraryRecordFile\` checks each one. */\nexport const libraryRecordFiles: readonly unknown[] = [\n${list}\n];\n`,
  );
}

/**
 * `assets library <search|ingest|credits|stats>`: search the shared asset library, refresh a source's
 * committed index from its upstream API, print credits for keys, or count entries.
 *
 * @internal
 */
export async function cmdLibrary(argv: readonly string[], generatedDir: string, fail: (message: string) => never): Promise<void> {
  const [verb, ...rest] = argv;
  if (verb === "ingest") {
    const targets = positional(rest);
    const names = targets.length === 0 || targets.includes("all") ? Object.keys(INGESTERS) : targets;
    for (const name of names) {
      const ingest = INGESTERS[name] ?? fail(`unknown library source: ${name} (one of ${Object.keys(INGESTERS).join(", ")})`);
      const limitFlag = flag(rest, "limit");
      const records = await ingest({ log: (line) => console.log(line), ...(limitFlag === undefined ? {} : { limit: Number(limitFlag) }), ...githubTokenOption() });
      const source = parseLibrarySourceId(name) ?? fail(`unknown library source: ${name}`);
      const file = recordFile(source, records);
      const issues = validateLibrary(file.records.map((record) => expandLibraryRecord(file.source, record)));
      if (issues.length > 0) fail(`${name}: ${issues.length} invalid record(s), first: ${issues[0]?.key} ${issues[0]?.problem}`);
      writeLibraryFile(generatedDir, file);
      console.log(`${name}: ${records.length} record(s) -> ${join(generatedDir, `${name}.json`)}`);
    }
    return;
  }
  const library = assetLibrary();
  if (verb === "search" || verb === "find") {
    const kindFlag = flag(rest, "kind");
    const kind = parseLibraryKind(kindFlag);
    if (kindFlag !== undefined && kind === undefined) fail(`--kind must be one of ${LIBRARY_KINDS.join(", ")}`);
    const tag = flag(rest, "tag");
    const sourceFlag = flag(rest, "source");
    const source = parseLibrarySourceId(sourceFlag);
    if (sourceFlag !== undefined && source === undefined) fail(`unknown --source ${sourceFlag}`);
    const hits = searchLibrary(library, positional(rest).join(" "), {
      ...(kind === undefined ? {} : { kind }),
      ...(tag === undefined ? {} : { tags: tag.split(",") }),
      ...(source === undefined ? {} : { source }),
      ...(rest.includes("--no-credit") ? { noCredit: true } : {}),
      limit: Number(flag(rest, "limit") ?? 20),
    });
    if (rest.includes("--json")) {
      console.log(JSON.stringify(hits.map((hit) => hit.entry), null, 2));
      return;
    }
    for (const { entry } of hits) {
      console.log(`${entry.key.padEnd(48)} ${entry.kind.padEnd(9)} ${libraryLicenseLabel(entry.license).padEnd(10)} ${entry.title} — ${entry.author}`);
    }
    console.log(`— ${hits.length} shown of ${library.length} entries · pull one with: assets pull <key> --dir public`);
    return;
  }
  if (verb === "credits") {
    const keys = positional(rest);
    const used = keys.map((key) => library.find((entry) => entry.key === key) ?? fail(`unknown library key: ${key}`));
    for (const section of libraryCreditSections(used)) {
      console.log(`## ${section.heading}`);
      for (const entry of section.entries) console.log(`- ${entry.label}: ${entry.detail ?? ""}${entry.href === undefined ? "" : ` (${entry.href})`}`);
    }
    return;
  }
  if (verb === "stats" || verb === undefined) {
    const counts = new Map<string, number>();
    for (const entry of library) counts.set(`${entry.source}/${entry.kind}`, (counts.get(`${entry.source}/${entry.kind}`) ?? 0) + 1);
    for (const [key, count] of [...counts.entries()].sort()) console.log(`${key.padEnd(24)} ${count}`);
    console.log(`library: ${library.length} entries`);
    const issues = validateLibrary(library);
    if (issues.length > 0) fail(`library: ${issues.length} invalid entr(ies), first: ${issues[0]?.key} ${issues[0]?.problem}`);
    return;
  }
  fail("usage: assets library <search <words> [--kind k] [--tag t] [--source s] [--no-credit] [--json] | ingest <source|all> | credits <key...> | stats>");
}

function githubTokenOption(): { githubToken?: string } {
  const token = resolveGithubToken();
  return token === undefined ? {} : { githubToken: token };
}
