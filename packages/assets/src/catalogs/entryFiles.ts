/** Path of a list's generated index. */
export function libraryIndexPath(list: LibraryList): string {
  return `${list.dir}/index.ts`;
}

/** Entry names under `dir`, from file paths: `asphalt/wet` for `asphalt/wet.ts`. */
export function libraryEntryNames(root: string, list: LibraryList): string[] {
  const base = join(root, list.dir);
  const names: string[] = [];
  const visit = (dir: string): void => {
    // walk-ok: one library folder of entry files, a few hundred at most.
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) visit(path);
      else if (name.endsWith(".ts") && name !== "index.ts" && !name.endsWith(".test.ts")) names.push(relative(base, path).split(sep).join("/").slice(0, -3));
    }
  };
  visit(base);
  return names.sort();
}

function identifier(name: string): string {
  const words = name.split(/[^A-Za-z0-9]+/).filter((word) => word.length > 0);
  const camel = words.map((word, index) => (index === 0 ? word.charAt(0).toLowerCase() + word.slice(1) : word.charAt(0).toUpperCase() + word.slice(1))).join("");
  return /^[0-9]/.test(camel) ? `entry${camel}` : camel;
}

/**
 * The generated index for a list. Loads every entry and throws when an entry's key is not its file
 * name, or two files map to one identifier.
 */
export async function renderLibraryIndex(root: string, list: LibraryList): Promise<string> {
  const names = libraryEntryNames(root, list);
  const ids = new Map<string, string>();
  for (const name of names) {
    const module: unknown = await import(pathToFileURL(join(root, list.dir, `${name}.ts`)).href);
    const entry: unknown = typeof module === "object" && module !== null ? Reflect.get(module, "default") : undefined;
    const key: unknown = typeof entry === "object" && entry !== null ? Reflect.get(entry, list.key) : undefined;
    if (key !== name) throw new Error(`${list.dir}/${name}.ts: ${list.key} is ${JSON.stringify(key)}; it must be "${name}", the file's own path`);
    const id = identifier(name);
    const clash = ids.get(id);
    if (clash !== undefined) throw new Error(`${list.dir}: ${clash}.ts and ${name}.ts both import as ${id}; rename one`);
    ids.set(id, name);
  }
  const imports = names.map((name) => `import ${identifier(name)} from "./${name}";`);
  const typeImport = list.type === undefined ? [] : [`import type { ${list.type.name} } from "${list.type.from}";`, ""];
  const items = names.map((name) => `  ${identifier(name)},`);
  const declaration = list.type === undefined ? `export const ${list.exportName} = [` : `export const ${list.exportName}: readonly ${list.type.name}[] = [`;
  return [
    "// GENERATED by `bun run gen library-index` from the entry files beside it. Add or edit an entry's own file, never this one.",
    ...typeImport,
    ...imports,
    "",
    `/** ${list.doc} */`,
    declaration,
    ...items,
    list.type === undefined ? "] as const;" : "];",
    "",
  ].join("\n");
}
