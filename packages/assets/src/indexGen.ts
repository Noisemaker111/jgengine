import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { readGlbFileMetrics } from "./assetBudget";
import type { GlbMetrics } from "./glbMetrics";
import { COLLISION_MESH_ASSET_IDS } from "./collisionMeshAssets";
import { readGlbClips, readGlbCollisionMesh, readGlbDims } from "./dims";
import { packExportName, type AssetSource, type CollisionMeshData, type IndexEntry, type ModelDims } from "./manifest";
import { sourceById } from "./sources";

export function keyFromFile(file: string): string {
  return file.replace(/\.gltf\.glb$/i, "").replace(/\.glb$/i, "");
}

/** Build a source-owned model entry, preserving optional measured bounds, collision, clips, and inventory. */
export function entryForFile(
  source: AssetSource,
  file: string,
  dims?: ModelDims,
  collisionMesh?: CollisionMeshData,
  clips?: readonly string[],
  metrics?: GlbMetrics,
): IndexEntry {
  return {
    id: `${source.id}/${keyFromFile(file)}`,
    source: source.id,
    categories: source.categories,
    file,
    ...(metrics === undefined ? {} : { metrics }),
    ...(dims === undefined ? {} : { dims }),
    ...(collisionMesh === undefined ? {} : { collisionMesh }),
    ...(clips === undefined ? {} : { clips }),
  };
}

function collectGlbFiles(dir: string): { file: string; full: string }[] {
  const found: { file: string; full: string }[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      found.push(...collectGlbFiles(full));
    } else if (/\.glb$/i.test(name)) {
      found.push({ file: name, full });
    }
  }
  return found;
}

function measureDims(bytes: Uint8Array): ModelDims | undefined {
  try {
    return readGlbDims(bytes) ?? undefined;
  } catch {
    return undefined;
  }
}

function measureCollisionMesh(bytes: Uint8Array): CollisionMeshData | undefined {
  try {
    return readGlbCollisionMesh(bytes) ?? undefined;
  } catch {
    return undefined;
  }
}

function measureClips(bytes: Uint8Array): readonly string[] | undefined {
  try {
    return readGlbClips(bytes) ?? undefined;
  } catch {
    return undefined;
  }
}

function entryFromGlb(source: AssetSource, file: string, full: string, resourceRoot: string): IndexEntry {
  let bytes: Uint8Array;
  try {
    bytes = readFileSync(full);
  } catch {
    return entryForFile(source, file);
  }
  const id = `${source.id}/${keyFromFile(file)}`;
  const collisionMesh = COLLISION_MESH_ASSET_IDS.has(id) ? measureCollisionMesh(bytes) : undefined;
  let metrics: GlbMetrics | undefined;
  try {
    metrics = readGlbFileMetrics(full, resourceRoot);
  } catch {
    metrics = undefined;
  }
  return entryForFile(source, file, measureDims(bytes), collisionMesh, measureClips(bytes), metrics);
}

export function indexSourceDir(source: AssetSource, dir: string): IndexEntry[] {
  const seen = new Set<string>();
  const entries: IndexEntry[] = [];
  for (const { file, full } of collectGlbFiles(dir).sort((a, b) => a.file.localeCompare(b.file))) {
    if (seen.has(file)) continue;
    seen.add(file);
    entries.push(entryFromGlb(source, file, full, dir));
  }
  return entries;
}

function jsonIdentifier(sourceId: string): string {
  return `s_${sourceId.replace(/[^a-zA-Z0-9]/g, "_")}`;
}

const GENERATED_HEADER = "// AUTO-GENERATED by `assets reindex`. Do not edit by hand.";

function orderedPacks(sourceIds: readonly string[]): { id: string; name: string; json: string }[] {
  const packs = [...sourceIds].sort((a, b) => a.localeCompare(b)).map((id) => ({ id, name: packExportName(id), json: jsonIdentifier(id) }));
  const seen = new Map<string, string>();
  for (const pack of packs) {
    const clash = seen.get(pack.name);
    if (clash !== undefined) throw new Error(`assets reindex: sources "${clash}" and "${pack.id}" both export as ${pack.name}`);
    seen.set(pack.name, pack.id);
  }
  return packs;
}

// One module per pack: a bundler keeps a module whole, so a pack shares a chunk only with the games that import it.
function renderPack(pack: { id: string; name: string; json: string }, typed: boolean): string {
  const lines = [GENERATED_HEADER];
  if (typed) lines.push(`import type { AssetPack, IndexEntry } from "../../manifest";`);
  lines.push(`import ${pack.json} from "../${pack.id}.json" with { type: "json" };`, "");
  lines.push(
    typed
      ? `export const ${pack.name}: AssetPack = { id: ${JSON.stringify(pack.id)}, entries: ${pack.json} as IndexEntry[] }; // type-escape: a JSON import widens the manifest's literal unions`
      : `export const ${pack.name} = { id: ${JSON.stringify(pack.id)}, entries: ${pack.json} };`,
  );
  return `${lines.join("\n")}\n`;
}

function renderPacks(sourceIds: readonly string[]): string {
  const packs = orderedPacks(sourceIds);
  const lines = [GENERATED_HEADER];
  for (const pack of packs) lines.push(`export { ${pack.name} } from "./pack/${pack.id}";`);
  return `${lines.join("\n")}\n`;
}

function renderBarrel(sourceIds: readonly string[], typed: boolean): string {
  const packs = orderedPacks(sourceIds);
  const lines = [GENERATED_HEADER];
  if (typed) lines.push(`import type { AssetPack, IndexEntry } from "../manifest";`);
  lines.push(`import {`, ...packs.map((pack) => `  ${pack.name},`), `} from "./packs";`, "");
  lines.push(
    "/** Every pulled pack. Importing this bundles the whole library; a game imports only its own packs from `./packs`. */",
    `export const generatedPacks${typed ? ": readonly AssetPack[]" : ""} = [`,
    ...packs.map((pack) => `  ${pack.name},`),
    "];",
    "",
    // Pure-annotated calls, so a bundle that imports this module without using these drops every pack.
    `function bySource(packs${typed ? ": readonly AssetPack[]" : ""})${typed ? ": Readonly<Record<string, readonly IndexEntry[]>>" : ""} {`,
    "  return Object.fromEntries(packs.map((pack) => [pack.id, pack.entries]));",
    "}",
    "",
    `function allEntries(packs${typed ? ": readonly AssetPack[]" : ""})${typed ? ": readonly IndexEntry[]" : ""} {`,
    "  return packs.flatMap((pack) => pack.entries);",
    "}",
    "",
    `export const generatedBySource = /* @__PURE__ */ bySource(generatedPacks);`,
    "",
    `export const generatedIndex = /* @__PURE__ */ allEntries(generatedPacks);`,
  );
  return `${lines.join("\n")}\n`;
}

/** Writes the generated pack modules and the barrel over every `<source>.json` already in `outDir`. */
export function writeIndexBarrels(outDir: string): void {
  const barrelIds = readdirSync(outDir)
    .filter((name) => name.endsWith(".json"))
    .map((name) => name.slice(0, -".json".length))
    .filter((id) => sourceById.has(id));
  const packDir = join(outDir, "pack");
  mkdirSync(packDir, { recursive: true });
  // Published installs only ship dist/; write JS modules there so a game can import a pack pulled after install.
  // Source-tree reindex keeps the TypeScript modules that the package build compiles.
  const extensions = /[/\\]src[/\\]generated$/i.test(outDir) ? (["ts"] as const) : (["ts", "js"] as const);
  for (const ext of extensions) {
    const typed = ext === "ts";
    for (const pack of orderedPacks(barrelIds)) writeFileSync(join(packDir, `${pack.id}.${ext}`), renderPack(pack, typed));
    writeFileSync(join(outDir, `packs.${ext}`), renderPacks(barrelIds));
    writeFileSync(join(outDir, `index.${ext}`), renderBarrel(barrelIds, typed));
  }
}

export interface ReindexResult {
  perSource: { source: string; count: number }[];
  total: number;
}

export function reindex(modelsDir: string, outDir: string): ReindexResult {
  mkdirSync(outDir, { recursive: true });
  const perSource: { source: string; count: number }[] = [];

  const subdirs = existsSync(modelsDir)
    ? readdirSync(modelsDir).filter((name) => statSync(join(modelsDir, name)).isDirectory())
    : [];

  for (const sourceId of subdirs.sort((a, b) => a.localeCompare(b))) {
    const source = sourceById.get(sourceId);
    if (source === undefined) {
      perSource.push({ source: `${sourceId} (unknown, skipped)`, count: 0 });
      continue;
    }
    const entries = indexSourceDir(source, join(modelsDir, sourceId));
    writeFileSync(join(outDir, `${sourceId}.json`), `${JSON.stringify(entries, null, 2)}\n`);
    perSource.push({ source: sourceId, count: entries.length });
  }

  writeIndexBarrels(outDir);
  return { perSource, total: perSource.reduce((sum, entry) => sum + entry.count, 0) };
}
